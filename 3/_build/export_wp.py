LINK_RE = re.compile(r'href="([a-z0-9-]+)\.html(#[a-z0-9-]+)?"')


def links(x):
    """slug.html → {{url:slug}} (index → home), рекурсивно."""
    if isinstance(x, str):
        def rep(m):
            key = "home" if m.group(1) == "index" else m.group(1)
            return 'href="{{url:%s}}%s"' % (key, m.group(2) or "")
        return LINK_RE.sub(rep, x)
    if isinstance(x, dict):
        return {k: links(v) for k, v in x.items()}
    if isinstance(x, list):
        return [links(v) for v in x]
    return x


def svc_fields(s, tr, lang, steps_head, shared_faq, chip_reviews):
    key = s["slug"]
    out = {k: s[k] for k in ("nav", "icon", "category", "home_items", "title", "description", "h1", "h1_gold", "lead",
                              "bullets", "years_text", "situations", "help_gold", "help_text", "tabs", "price",
                              "about_text", "reviews_gold", "seo", "faq", "final_h2", "final_gold", "docs")}
    out["situations_text"] = s.get("situations_text", "")
    out["steps"] = s.get("steps") or (steps_head + [s["step_last"]])
    out["faq"] = [shared_faq] + s["faq"]
    # фото героя: як у дизайні 3 (lawyer-office → нове фото адвоката, lawyer-hero лишається)
    out["hero_preset"] = "lawyer-standing" if s["hero_img"] == "lawyer-office" else "lawyer-hero"
    out["hero_alt"] = s["hero_alt"] if s["hero_img"] != "lawyer-office" else tr.gettext("Адвокат Сергій Мазур")
    # відгуки — лише реальні
    src = REAL_REVIEWS.get(key)
    if src == "own":
        out["reviews"], out["reviews_label"] = s["reviews"], s.get("reviews_rating", "")
    elif src == "kryt":
        out["reviews"], out["reviews_label"] = KRYT_REVIEWS[lang], ("Відгуки клієнтів" if lang == "uk" else "Отзывы клиентов")
    elif src == "chip":
        out["reviews"], out["reviews_label"] = chip_reviews, ("Відгуки водіїв" if lang == "uk" else "Отзывы водителей")
    else:
        out["reviews"], out["reviews_label"] = [], ""
    # персоналізація
    p = PERSONAL.get(key)
    if p:
        L = p[lang]
        out.update(hero_image=p["hero_image"], hero_alt=L["hero_alt"], hero_cta=L["hero_cta"], eyebrow=L["eyebrow"],
                   lawyer_badge=p["lawyer_badge"], showcase_title=L["showcase_title"], showcase_gold=L["showcase_gold"],
                   showcase_text=L["showcase_text"], showcase=L["showcase"])
        out["faq"] = out["faq"] + L["faq_extra"]
    # ціна чіп-карти — з макета (4 200 ₴ з 02.11.2026)
    return out


