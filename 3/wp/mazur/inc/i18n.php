/**
 * Переклад рядка шаблону (український рядок — ключ).
 * Як у статичній збірці: ключ — обрізаний рядок, пробіли навколо зберігаються.
 */
function mz_t( $text ) {
	if ( 'ru' !== mz_lang() || '' === trim( (string) $text ) ) {
		return $text;
	}
	$dict = mz_dict();
	$key  = trim( $text );
	if ( isset( $dict[ $key ] ) ) {
		return str_replace( $key, $dict[ $key ], $text );
	}
	return $text;
}

/** echo + esc_html */
function mz_e( $text ) {
	echo esc_html( mz_t( $text ) );
}

/** esc_attr(mz_t()) */
function mz_a( $text ) {
	return esc_attr( mz_t( $text ) );
}
