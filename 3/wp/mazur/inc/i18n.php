/** Поточна мова: 'uk' або 'ru'. */
function mz_lang() {
	if ( function_exists( 'pll_current_language' ) ) {
		$l = pll_current_language( 'slug' );
		if ( $l ) {
			return $l;
		}
	}
	return 'uk';
}

/** Мова конкретного запису (для адмінки / імпорту). */
function mz_post_lang( $post_id ) {
	if ( function_exists( 'pll_get_post_language' ) ) {
		$l = pll_get_post_language( $post_id, 'slug' );
		if ( $l ) {
			return $l;
		}
	}
	return 'uk';
}

